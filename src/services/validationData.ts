export function getSeededDatabase(technicianName: string = TECHNICIAN_DEFAULT_NAME): InventoryDatabase {
  return {
    version: '1.0.0',
    lastUpdated: new Date().toISOString(),
    technicianName,
    types: initialTypes,
    groups: initialGroups,
    subgroups: initialSubgroups,
    articles: initialArticles.map((a) => ({
      ...a,
      description: a.description.replace(/Carmen\.$/, `${technicianName}.`),
    })),
    movements: initialMovements.map((m) => ({
      ...m,
      technicianName,
    })),
  };
}

export function getEmptyDatabase(technicianName: string = TECHNICIAN_DEFAULT_NAME): InventoryDatabase {
  return {
    version: '1.0.0',
    lastUpdated: new Date().toISOString(),
    technicianName,
    types: [],
    groups: [],
    subgroups: [],
    articles: [],
    movements: [],
  };
}
